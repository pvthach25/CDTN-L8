
CREATE TABLE IF NOT EXISTS customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS service_center (
    center_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_name VARCHAR(150) NOT NULL,
    address TEXT
);

CREATE TABLE IF NOT EXISTS technician (
    technician_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id INTEGER NOT NULL,
    technician_name VARCHAR(150) NOT NULL,

    CONSTRAINT fk_technician_center
        FOREIGN KEY (center_id)
        REFERENCES service_center(center_id)
);

CREATE TABLE IF NOT EXISTS ticket (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    technician_id INTEGER NOT NULL,
    center_id INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    closed_at TIMESTAMPTZ,

    CONSTRAINT fk_ticket_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id),

    CONSTRAINT fk_ticket_technician
        FOREIGN KEY (technician_id)
        REFERENCES technician(technician_id),

    CONSTRAINT fk_ticket_center
        FOREIGN KEY (center_id)
        REFERENCES service_center(center_id),

    CONSTRAINT chk_ticket_status
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),

    CONSTRAINT chk_ticket_closed_at
        CHECK (status <> 'CLOSED' OR closed_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS survey_response (
    response_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL UNIQUE,
    csat_score INTEGER NOT NULL,
    nps_score INTEGER NOT NULL,
    comment TEXT,
    responded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_survey_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES ticket(ticket_id),

    CONSTRAINT chk_csat_score
        CHECK (csat_score BETWEEN 1 AND 5),

    CONSTRAINT chk_nps_score
        CHECK (nps_score BETWEEN 0 AND 10)
);

-- Chỉ cho phép khảo sát khi ticket đã CLOSED.
CREATE OR REPLACE FUNCTION validate_survey_ticket()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM ticket
        WHERE ticket_id = NEW.ticket_id
          AND status = 'CLOSED'
    ) THEN
        RAISE EXCEPTION
            'Survey requires a CLOSED ticket';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_survey_ticket
ON survey_response;

CREATE TRIGGER trg_validate_survey_ticket
BEFORE INSERT OR UPDATE OF ticket_id
ON survey_response
FOR EACH ROW
EXECUTE FUNCTION validate_survey_ticket();
